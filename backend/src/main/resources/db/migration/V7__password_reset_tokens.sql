-- Fondations de récupération de mot de passe et d'invalidation JWT.
-- Cette migration ne modifie aucune table existante.

CREATE TABLE public.password_reset_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id INTEGER NOT NULL
        REFERENCES public.utilisateurs(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ
);

CREATE INDEX idx_password_reset_token_utilisateur
    ON public.password_reset_token (utilisateur_id);

CREATE INDEX idx_password_reset_token_expiration
    ON public.password_reset_token (expires_at);

CREATE TABLE public.utilisateur_auth_state (
    utilisateur_id INTEGER PRIMARY KEY
        REFERENCES public.utilisateurs(id) ON DELETE CASCADE,
    token_version INTEGER NOT NULL DEFAULT 0
        CHECK (token_version >= 0)
);

INSERT INTO public.utilisateur_auth_state (utilisateur_id, token_version)
SELECT u.id, 0
FROM public.utilisateurs u
ON CONFLICT (utilisateur_id) DO NOTHING;
